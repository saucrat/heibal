export function tr(lang, key, vars) {
  const table = dict[lang] || dict.fr;
  let text = table[key] ?? dict.fr[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}
